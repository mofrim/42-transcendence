import React, { useState, useCallback } from 'react';
import axios from 'axios';
import type { EventLogEntry } from '../ui/ingame/EventLogItems';
import { EventLogContext } from '../contexts/EventLogContext.tsx';
import {
    GameEvent,
    API_EVENTLOG,
    API_USER,
    type ApiResponse,
    type EventDataQuestCompleted,
    EventType,
} from 'ftr-common/sharedTypes';
import {
    EVENT_TIME_FORMAT,
    MAX_EVENT_LOG_ENTRIES,
    describeGameEvent,
    getGameEventProfileNicknames,
} from '../lib/eventLogUtils.ts';

export const EventLogProvider: React.FC<{ children: React.ReactNode }> = ({
    children,
}) => {
    const [events, setEvents] = useState<EventLogEntry[]>([]);

    const appendEvent = useCallback(async (event: GameEvent) => {
        // avoid double entries as useMatchHistory's saveMatchResult is already
        // storing the match-result in DB
        if (event.eventType === EventType.MiniGameResult) {
            return;
        }

        const now = new Date();
        const timestamp = EVENT_TIME_FORMAT.format(now);
        const description = describeGameEvent(event);

        try {
            const response = await axios.post<ApiResponse>(API_EVENTLOG.root, {
                eventType: event.eventType,
                data: event.data,
                logtime: now,
            });

            // using id generated by DB for EventLog-ID.. which should be unique
            // enough 8)
            const ev: EventLogEntry = {
                id: response.data.id!.toString(),
                timestamp,
                description,
                profileNicknames: getGameEventProfileNicknames(event),
            };

            setEvents((currentEvents) =>
                [...currentEvents, ev].slice(-MAX_EVENT_LOG_ENTRIES)
            );
        } catch (error) {
            console.error(
                '[EventLog] Failed to save event to database:',
                error
            );
            return;
        }

        // update user quests in DB
        if (event.eventType == EventType.QuestCompleted) {
            try {
                await axios.post<ApiResponse>(API_USER.quests, {
                    quest: (event.data as EventDataQuestCompleted).questId,
                });
            } catch (err) {
                console.error(
                    '[EventLog] storing QuestStatus in users-table failed:',
                    err
                );
                return;
            }
        }
        console.log(`[EventLog] event ${event.eventType} saved`);
    }, []);

    return (
        <EventLogContext.Provider
            value={{
                events,
                appendEvent,
                setEvents,
            }}
        >
            {children}
        </EventLogContext.Provider>
    );
};
